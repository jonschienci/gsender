const {test}=require('node:test'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
test('visualizer telemetry is opt-in, passive, bounded and reports frame stalls during a running job', async()=>{
    const {watchVisualizer,samples}=await import('../ui/visualizer-benchmark.mjs');
    const dom=new JSDOM('<svg></svg>',{url:'http://localhost/pendant/?benchmark=visualizer'});
    const win=dom.window,svg=win.document.querySelector('svg'),records=[],frames=new Map();
    let time=10,next=0;
    Object.defineProperty(win.performance,'now',{value:()=>time});
    win.requestAnimationFrame=fn=>{frames.set(++next,fn);return next;};
    win.cancelAnimationFrame=id=>frames.delete(id);
    const frame=stamp=>{time=stamp;const batch=[...frames.values()];frames.clear();batch.forEach(fn=>fn(stamp));};
    const send=(type,stamp,id=1)=>{const e=new win.Event(type,{bubbles:true,cancelable:true});
        Object.defineProperties(e,{timeStamp:{value:stamp},pointerId:{value:id}});svg.dispatchEvent(e);assert.equal(e.defaultPrevented,false);};
    let workflowState='running';
    const stop=watchVisualizer(svg,()=>({workflowState,fileLoaded:true}),{win,emit:r=>records.push(r)});
    send('pointerdown',5);frame(16);time=20;send('pointermove',18);frame(116);
    send('pointerup',115);frame(132);frame(160);
    const report=records.find(r=>r.event==='gesture');
    assert.equal(report.kind,'pan');assert.equal(report.contextStart.workflowState,'running');
    assert.equal(report.frameGapMs.max,100);assert.equal(report.framesOver50Ms,1);
    assert.equal(report.eventToRafMs.max,98);assert.equal(report.longTasks,null);
    assert.equal(frames.size,0);
    time=200;send('pointerdown',200);send('pointerdown',200,2);
    stop();assert.equal(records.at(-1).kind,'pinch');assert.equal(records.at(-1).reason,'disposed');assert.equal(frames.size,0);
    const count=records.length;send('pointermove',200);assert.equal(records.length,count);
    const s=samples();for(let i=0;i<9000;i++)s.add(i);assert.equal(s.result().dropped,808);assert.equal(s.result().max,8999);
    dom.reconfigure({url:'http://localhost/pendant/'});
    const inactive=watchVisualizer(svg,()=>({}),{win,emit:()=>assert.fail('Disabled benchmark logged')});
    send('pointerdown',200);assert.equal(frames.size,0);inactive();dom.window.close();
});
